#!/usr/bin/env Rscript
args <- commandArgs(trailingOnly=TRUE)
if(length(args)!=3) stop('Usage: Rscript task12_group_a_fastbaps.R ALIGNMENT PRIOR OUTPUT_DIRECTORY')
suppressPackageStartupMessages(library(fastbaps))
suppressPackageStartupMessages(library(ape))
prior <- switch(args[2], optimised.symmetric='optimise.symmetric', optimised.baps='optimise.baps', symmetric='symmetric', baps='baps', stop('Unknown prior'))
out <- args[3]; if(dir.exists(out)) stop('Output exists; refusing overwrite')
dir.create(out,recursive=TRUE); set.seed(20261002)
start <- Sys.time(); sparse <- import_fasta_sparse_nt(args[1]); expected <- colnames(sparse$snp.matrix)
cat('Input genomes',length(expected),' retained fastbaps sites',nrow(sparse$snp.matrix),'\n')
sparse <- optimise_prior(sparse,type=prior,n.cores=2)
h <- fast_baps(sparse,k.init=length(expected),n.cores=2)
p <- best_baps_partition(sparse,h)
stopifnot(setequal(names(p),expected),!anyDuplicated(names(p)),!anyNA(p))
write.table(data.frame(accession=names(p),cluster=as.integer(p)),file=file.path(out,'clusters.tsv'),sep='\t',row.names=FALSE,quote=FALSE)
saveRDS(list(prior=sparse$prior,prior_type=sparse$prior.type,hierarchy=h,partition=p),file.path(out,'model.rds'))
write.tree(as.phylo(h),file.path(out,'clustering-hierarchy.nwk'))
writeLines(capture.output(sessionInfo()),file.path(out,'sessionInfo.txt'))
write.table(data.frame(input=args[1],prior_api=prior,n=length(expected),retained_sites=nrow(sparse$snp.matrix),clusters=length(unique(p)),elapsed_seconds=as.numeric(difftime(Sys.time(),start,units='secs')),fastbaps=as.character(packageVersion('fastbaps'))),file=file.path(out,'run.tsv'),sep='\t',row.names=FALSE,quote=FALSE)
